// Reading Claude's session store.
//
// Transcripts are JSONL in projects/<encoded-cwd>/<uuid>.jsonl and can run to
// hundreds of KB, so metadata is sampled from the head and tail rather than by
// parsing the whole file. Records of interest:
//
//   head   cwd, version, gitBranch, timestamp, first user message
//   tail   custom-title, agent-name, agent-color, last-prompt  (last wins)
//
// Live sessions come from sessions/<pid>.json, which carries pid and a
// busy/idle status.

import fs from 'node:fs'
import path from 'node:path'
import { P, exists, decodeProject, encodeProject } from './paths.mjs'

const HEAD_BYTES = 16 * 1024
const TAIL_BYTES = 128 * 1024

function parseLines(text, onObject) {
  for (const line of text.split('\n')) {
    const t = line.trim()
    if (!t || t[0] !== '{') continue
    try { onObject(JSON.parse(t)) } catch { /* truncated or partial line */ }
  }
}

function textOf(message) {
  if (!message) return ''
  const c = message.content
  if (typeof c === 'string') return c
  if (Array.isArray(c)) {
    return c.filter((b) => b && b.type === 'text').map((b) => b.text).join(' ')
  }
  return ''
}

// Prompts arrive wrapped in harness scaffolding — slash-command envelopes,
// system reminders, and the local-command caveat. None of that identifies a
// session, so it is stripped before the text is used as a fallback title.
const NOISE = [
  /^Caveat:\s*The messages below were generated by[^]*?$/i,
  /^Your task is to\b/i,
]

function cleanPrompt(s) {
  const text = String(s || '')
    .replace(/<command-(name|message|args)>[^]*?<\/command-\1>/g, ' ')
    .replace(/<local-command-[^>]*>[^]*?<\/local-command-[^>]*>/g, ' ')
    .replace(/<system-reminder>[^]*?<\/system-reminder>/g, ' ')
    .replace(/<[^>]*>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  // Drop a leading caveat sentence but keep whatever the user actually typed
  // after it.
  const stripped = text.replace(/^Caveat:\s*The messages below were generated by the user while running local commands\.\s*DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to\.\s*/i, '').trim()
  if (!stripped) return ''
  if (NOISE.some((re) => re.test(stripped)) && stripped.length < 80) return ''
  return stripped
}

export function readSessionMeta(file) {
  let st
  try { st = fs.statSync(file) } catch { return null }
  const size = st.size
  const meta = {
    id: path.basename(file, '.jsonl'),
    file,
    size,
    mtime: st.mtimeMs,
    cwd: null,
    version: null,
    gitBranch: null,
    title: null,
    agentName: null,
    color: null,
    lastPrompt: null,
    firstPrompt: null,
    startedAt: null,
  }
  if (size === 0) return meta

  let fd
  try { fd = fs.openSync(file, 'r') } catch { return meta }
  try {
    const headLen = Math.min(size, HEAD_BYTES)
    const head = Buffer.alloc(headLen)
    fs.readSync(fd, head, 0, headLen, 0)
    parseLines(head.toString('utf8'), (o) => {
      if (!meta.cwd && o.cwd) meta.cwd = o.cwd
      if (!meta.version && o.version) meta.version = o.version
      if (!meta.gitBranch && o.gitBranch) meta.gitBranch = o.gitBranch
      if (!meta.startedAt && o.timestamp) meta.startedAt = Date.parse(o.timestamp) || null
      if (!meta.firstPrompt && o.type === 'user' && o.message) {
        const t = cleanPrompt(textOf(o.message))
        if (t) meta.firstPrompt = t
      }
      if (o.type === 'custom-title' && o.customTitle) meta.title = o.customTitle
      if (o.type === 'agent-name' && o.agentName) meta.agentName = o.agentName
    })

    if (size > headLen) {
      const tailLen = Math.min(size, TAIL_BYTES)
      const tail = Buffer.alloc(tailLen)
      fs.readSync(fd, tail, 0, tailLen, size - tailLen)
      let text = tail.toString('utf8')
      // Drop a leading partial line.
      const nl = text.indexOf('\n')
      if (nl !== -1 && size > tailLen) text = text.slice(nl + 1)
      parseLines(text, (o) => {
        if (o.type === 'custom-title' && o.customTitle) meta.title = o.customTitle
        if (o.type === 'agent-name' && o.agentName) meta.agentName = o.agentName
        if (o.type === 'agent-color' && o.agentColor) meta.color = o.agentColor
        if (o.type === 'last-prompt' && o.lastPrompt) meta.lastPrompt = cleanPrompt(o.lastPrompt)
        if (!meta.cwd && o.cwd) meta.cwd = o.cwd
      })
    }
  } finally {
    fs.closeSync(fd)
  }
  return meta
}

export function displayTitle(meta) {
  if (!meta) return 'untitled'
  const t = meta.title || meta.agentName
  if (t) return t
  const p = meta.lastPrompt || meta.firstPrompt
  if (p) return p.length > 60 ? p.slice(0, 57) + '…' : p
  return meta.id.slice(0, 8)
}

// Every project directory that holds transcripts.
export function projectDirs() {
  if (!exists(P.projects)) return []
  return fs.readdirSync(P.projects, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
}

// All transcripts, newest first, without reading their contents.
export function listTranscripts() {
  const out = []
  for (const dir of projectDirs()) {
    const full = path.join(P.projects, dir)
    let entries
    try { entries = fs.readdirSync(full, { withFileTypes: true }) } catch { continue }
    for (const e of entries) {
      if (!e.isFile() || !e.name.endsWith('.jsonl')) continue
      const file = path.join(full, e.name)
      let st
      try { st = fs.statSync(file) } catch { continue }
      out.push({
        id: path.basename(e.name, '.jsonl'),
        project: dir,
        file,
        size: st.size,
        mtime: st.mtimeMs,
      })
    }
  }
  out.sort((a, b) => b.mtime - a.mtime)
  return out
}

// Hydrate the newest `limit` transcripts with their metadata. The rest are
// returned with only what stat gave us — the Sessions screen never shows them
// until the list is filtered, at which point they are hydrated on demand.
export function listSessions({ limit = 80 } = {}) {
  const all = listTranscripts()
  const hydrated = []
  for (let i = 0; i < all.length; i++) {
    const t = all[i]
    if (i < limit) {
      const meta = readSessionMeta(t.file)
      hydrated.push({ ...t, ...meta, hydrated: true })
    } else {
      hydrated.push({ ...t, cwd: null, title: null, hydrated: false })
    }
  }
  return hydrated
}

export function hydrate(entry) {
  if (entry.hydrated) return entry
  const meta = readSessionMeta(entry.file)
  return { ...entry, ...meta, hydrated: true }
}

function pidAlive(pid) {
  if (!pid) return false
  try { process.kill(pid, 0); return true } catch (err) { return err.code === 'EPERM' }
}

// Sessions currently running on this machine.
export function listLive() {
  if (!exists(P.sessions)) return []
  const out = []
  for (const name of fs.readdirSync(P.sessions)) {
    if (!name.endsWith('.json')) continue
    const file = path.join(P.sessions, name)
    let data
    try { data = JSON.parse(fs.readFileSync(file, 'utf8')) } catch { continue }
    if (!data.sessionId) continue
    const alive = pidAlive(data.pid)
    if (!alive) continue
    out.push({
      pid: data.pid,
      id: data.sessionId,
      cwd: data.cwd || null,
      name: data.name || null,
      status: data.status || 'idle',
      kind: data.kind || 'interactive',
      version: data.version || null,
      startedAt: data.startedAt || null,
      updatedAt: data.updatedAt || null,
      file,
    })
  }
  out.sort((a, b) => (b.updatedAt || 0) - (a.updatedAt || 0))
  return out
}

// Clear out sessions/*.json whose process is gone.
export function pruneStaleLiveFiles() {
  if (!exists(P.sessions)) return 0
  let n = 0
  for (const name of fs.readdirSync(P.sessions)) {
    if (!name.endsWith('.json')) continue
    const file = path.join(P.sessions, name)
    try {
      const data = JSON.parse(fs.readFileSync(file, 'utf8'))
      if (!pidAlive(data.pid)) { fs.rmSync(file, { force: true }); n++ }
    } catch {
      fs.rmSync(file, { force: true }); n++
    }
  }
  return n
}

// ── Live activity ────────────────────────────────────────────────────
// What a running session is doing right now, read from the tail of its
// transcript. Cached on (size, mtime) because the Dispatch screen asks for
// this once a second and transcripts run to megabytes.

const activityCache = new Map()

function summariseToolInput(name, input) {
  if (!input || typeof input !== 'object') return ''
  const pick = (...keys) => {
    for (const k of keys) if (typeof input[k] === 'string' && input[k]) return input[k]
    return ''
  }
  switch (name) {
    case 'Bash': return pick('command', 'description')
    case 'Read': case 'Write': case 'Edit': case 'NotebookEdit': return pick('file_path')
    case 'Glob': case 'Grep': return pick('pattern')
    case 'WebFetch': return pick('url')
    case 'WebSearch': return pick('query')
    case 'Task': case 'Agent': return pick('description', 'prompt')
    case 'Skill': return pick('skill')
    default: return pick('description', 'command', 'file_path', 'pattern', 'query', 'prompt')
  }
}

export function readActivity(file) {
  let st
  try { st = fs.statSync(file) } catch { return null }
  const key = `${file}:${st.size}:${st.mtimeMs}`
  const hit = activityCache.get(key)
  if (hit) return hit

  const out = {
    model: null,
    contextTokens: 0,
    outputTokens: 0,
    lastPrompt: null,
    activity: null,       // what it is doing now
    activityKind: null,   // 'tool' | 'text' | 'user'
    tools: 0,
    turns: 0,
    at: st.mtimeMs,
  }

  let fd
  try { fd = fs.openSync(file, 'r') } catch { return null }
  try {
    const len = Math.min(st.size, TAIL_BYTES)
    const buf = Buffer.alloc(len)
    fs.readSync(fd, buf, 0, len, st.size - len)
    let text = buf.toString('utf8')
    const nl = text.indexOf('\n')
    if (nl !== -1 && st.size > len) text = text.slice(nl + 1)

    parseLines(text, (o) => {
      if (o.type === 'assistant') {
        out.turns++
        const m = o.message || {}
        if (m.model) out.model = m.model
        const u = m.usage
        if (u) {
          out.contextTokens = (u.input_tokens || 0) + (u.cache_read_input_tokens || 0) + (u.cache_creation_input_tokens || 0)
          out.outputTokens = u.output_tokens || 0
        }
        for (const b of m.content || []) {
          if (!b || typeof b !== 'object') continue
          if (b.type === 'tool_use') {
            out.tools++
            const detail = cleanPrompt(summariseToolInput(b.name, b.input))
            out.activity = detail ? `${b.name}  ${detail}` : b.name
            out.activityKind = 'tool'
          } else if (b.type === 'text' && b.text?.trim()) {
            out.activity = cleanPrompt(b.text)
            out.activityKind = 'text'
          }
        }
      } else if (o.type === 'last-prompt' && o.lastPrompt) {
        out.lastPrompt = cleanPrompt(o.lastPrompt)
      } else if (o.type === 'user' && o.message && !o.isSidechain) {
        const t = cleanPrompt(textOf(o.message))
        if (t) { out.activity = t; out.activityKind = 'user' }
      }
    })
  } finally {
    fs.closeSync(fd)
  }

  // Keep the cache from growing without bound across a long session.
  if (activityCache.size > 32) activityCache.clear()
  activityCache.set(key, out)
  return out
}

// ── Subagents ────────────────────────────────────────────────────────
//
// Whether a session has agents running is decided from the parent transcript,
// not from the files in subagents/: a dispatch is a `tool_use` named Agent or
// Task, and it is finished when a `tool_result` carries the matching id. An
// unmatched dispatch is still running.
//
// The subagent transcripts cannot be tied back to a specific dispatch — the
// parent records carry no promptId — so cl does not pretend to. It reports the
// dispatches, which it can be sure of.
//
// Parsing is incremental: only the bytes appended since the last call are
// read, so watching a busy 3MB transcript costs nothing per frame.

const agentState = new Map() // file -> { offset, agents: Map, mtime }

const AGENT_TOOLS = new Set(['Agent', 'Task'])

function agentLabel(input = {}) {
  return input.description
    || (typeof input.prompt === 'string' ? cleanPrompt(input.prompt).slice(0, 60) : '')
    || ''
}

export function readAgents(file) {
  let st
  try { st = fs.statSync(file) } catch { return [] }

  let state = agentState.get(file)
  // A shrunk file means it was replaced; start over rather than read garbage.
  if (!state || st.size < state.offset) {
    state = { offset: 0, agents: new Map(), mtime: 0 }
    agentState.set(file, state)
  }
  if (st.size === state.offset) return summariseAgents(state)

  let fd
  try { fd = fs.openSync(file, 'r') } catch { return summariseAgents(state) }
  try {
    const len = st.size - state.offset
    const buf = Buffer.alloc(len)
    fs.readSync(fd, buf, 0, len, state.offset)
    const text = buf.toString('utf8')

    // Stop at the last complete line; the tail may be mid-write.
    const lastNl = text.lastIndexOf('\n')
    if (lastNl === -1) return summariseAgents(state)
    state.offset += Buffer.byteLength(text.slice(0, lastNl + 1), 'utf8')

    parseLines(text.slice(0, lastNl + 1), (o) => {
      if (o.isSidechain) return
      const m = o.message
      if (!m) return
      const ts = Date.parse(o.timestamp) || Date.now()
      for (const b of m.content || []) {
        if (!b || typeof b !== 'object') continue
        if (b.type === 'tool_use' && AGENT_TOOLS.has(b.name)) {
          state.agents.set(b.id, {
            id: b.id,
            type: b.input?.subagent_type || b.input?.agentType || 'agent',
            label: agentLabel(b.input),
            startedAt: ts,
            endedAt: null,
          })
        } else if (b.type === 'tool_result' && state.agents.has(b.tool_use_id)) {
          const a = state.agents.get(b.tool_use_id)
          if (a.endedAt === null) a.endedAt = ts
        }
      }
    })
  } finally {
    fs.closeSync(fd)
  }
  state.mtime = st.mtimeMs
  return summariseAgents(state)
}

function summariseAgents(state) {
  return [...state.agents.values()].sort((a, b) => {
    // Running first, newest dispatch first within each group.
    const ra = a.endedAt === null ? 0 : 1
    const rb = b.endedAt === null ? 0 : 1
    return ra - rb || b.startedAt - a.startedAt
  })
}

// Dispatches with no result yet. In practice this is almost always empty:
// Claude writes the tool_use and tool_result records together once the tool
// has finished, so an agent that is still working has not been written to the
// parent transcript at all. Kept because it is correct when it does fire, but
// `subagentActivity` is the signal that actually catches live work.
export function runningAgents(file) {
  return readAgents(file).filter((a) => a.endedAt === null)
}

// Live subagent work, inferred from the sidechain transcripts being appended
// to. Unlike the parent transcript these are written as the agent works, so a
// file touched seconds ago means an agent is running right now.
//
// This is a heuristic — it reads file activity, not a status field, because
// Claude publishes no such field for subagents. A file also gets one final
// write on completion, so an agent can look "active" for ACTIVE_MS after it
// finishes.
const ACTIVE_MS = 25_000

export function subagentActivity(live, now = Date.now()) {
  const out = { active: 0, total: 0, newest: 0, files: [] }
  if (!live?.cwd || !live?.id) return out
  const dir = path.join(P.projects, encodeProject(live.cwd), live.id, 'subagents')
  if (!exists(dir)) return out
  let entries
  try { entries = fs.readdirSync(dir) } catch { return out }
  for (const name of entries) {
    if (!name.endsWith('.jsonl')) continue
    let st
    try { st = fs.statSync(path.join(dir, name)) } catch { continue }
    out.total++
    if (st.mtimeMs > out.newest) out.newest = st.mtimeMs
    const age = now - st.mtimeMs
    if (age <= ACTIVE_MS) {
      out.active++
      out.files.push({
        id: name.replace(/^agent-/, '').replace(/\.jsonl$/, ''),
        mtime: st.mtimeMs,
        size: st.size,
        age,
      })
    }
  }
  out.files.sort((a, b) => b.mtime - a.mtime)
  return out
}

// Path to a live session's transcript, if it exists.
export function transcriptFor(live) {
  if (!live?.cwd || !live?.id) return null
  const dir = path.join(P.projects, encodeProject(live.cwd))
  const file = path.join(dir, `${live.id}.jsonl`)
  return exists(file) ? file : null
}

// Stable signature of the live set — used to decide whether a redraw is needed.
export function liveSignature(list) {
  return list.map((l) => `${l.id}:${l.status}:${l.updatedAt}`).sort().join('|')
}

export function deleteSession(entry) {
  fs.rmSync(entry.file, { force: true })
  // Sidecar directory of the same name, when one exists.
  const side = entry.file.replace(/\.jsonl$/, '')
  if (exists(side)) {
    try { fs.rmSync(side, { recursive: true, force: true }) } catch { /* best effort */ }
  }
}

// Real working directory for a project folder: exact when a session recorded
// it, otherwise the lossy decode.
export function projectCwd(projectDir, sessions) {
  const withCwd = sessions?.find((s) => s.project === projectDir && s.cwd)
  if (withCwd) return withCwd.cwd
  const dir = path.join(P.projects, projectDir)
  try {
    for (const e of fs.readdirSync(dir)) {
      if (!e.endsWith('.jsonl')) continue
      const meta = readSessionMeta(path.join(dir, e))
      if (meta?.cwd) return meta.cwd
    }
  } catch { /* fall through */ }
  return decodeProject(projectDir)
}
